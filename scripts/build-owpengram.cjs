'use strict';

// Metro receives this self-contained browser build, never teleproto's Node path.
const path = require('node:path');
const fs = require('node:fs');
const esbuild = require('esbuild');
const root = path.resolve(__dirname, '..');

async function build() {
  const version = require('teleproto/package.json').version;
  if (version !== '1.232.1') throw new Error('Expected the audited teleproto version 1.232.1');
  const result = await esbuild.build({
    absWorkingDir: root,
    entryPoints: ['transport/owpengram-entry.js'],
    outfile: 'transport/owpengram.bundle.cjs',
    bundle: true,
    platform: 'browser',
    format: 'cjs',
    target: 'es2020',
    minify: true,
    legalComments: 'eof',
    metafile: true,
    write: false,
    logLevel: 'warning',
    banner: { js: '// Generated by scripts/build-owpengram.cjs. Direct OwpenGram mobile transport.' },
  });
  for (const [file, details] of Object.entries(result.metafile.inputs)) {
    if (/\/platform\/[^/]+\/node\.js$|\/cifrante\.node\./.test(file)) {
      throw new Error('Unexpected Node implementation in mobile bundle: ' + file);
    }
    for (const dependency of details.imports) {
      if (dependency.external) throw new Error('Unbundled runtime import: ' + dependency.path);
    }
  }
  for (const file of result.outputFiles) fs.writeFileSync(file.path, file.contents);
  console.log('Built transport/owpengram.bundle.cjs with browser platform adapters, no external runtime imports.');
}

if (require.main === module) build().catch((error) => { console.error(error.message); process.exitCode = 1; });
module.exports = { build };
